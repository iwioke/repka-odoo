from odoo import fields, models

class UfsContract(models.Model):
    _name = "ufs.contract"
    _description = "UFS Contract"
    _order = "expiration_date desc"
    _inherit = ['mail.thread', 'mail.activity.mixin']
    active = fields.Boolean(string="Active")
    company_id = fields.Many2one(string="Company", required=True, comodel_name="res.company")
    contract_html = fields.Html(string="Contract Body")
    contract_type = fields.Selection(string="Contract Type", selection=[("placeholder", "Placeholder")])
    count_authority_text = fields.Char(string="Authority Text(partner)", translate=True)
    count_signed_by_partner_id = fields.Many2one(string="Signed by(partner)", comodel_name="res.partner")
    currency_compute_rule = fields.Selection(string="Currency Compute Rule", selection=[("placeholder", "Placeholder")])
    currency_id = fields.Many2one(string="Currency", comodel_name="res.currency")
    doc_preference_ids = fields.One2many(string="Document Delivery Preferences", comodel_name="ufs.contract.doc.preference", inverse_name="contract_id")
    expiration_date = fields.Date(string="Expiration Date", help="No date means Termless Contract")
    has_message = fields.Boolean(string="Has Message", readonly=True, store=False)
    invoicing_currency_id = fields.Many2one(string="Invoice Currency", help="While invoice creation, if this currency is set, invoice will be created in that currency.", comodel_name="res.currency")
    is_cash_expected = fields.Boolean(string="Cash Expected", help="If you expect Cash for order Payment, mark order as Cash, so we will create Invoices with Cash attributes")
    is_order_agreement = fields.Boolean(string="Is an order agreement")
    is_valid = fields.Boolean(string="Is Valid", readonly=True, store=False)
    load_fail_penalty = fields.Float(string="Load Fail Penalty, %")
    load_fail_penalty_terms = fields.Char(string="Load Fail Penalty")
    n_days_count = fields.Integer(string="N")
    name = fields.Char(string="Name", readonly=True)
    needs_currency_recalc = fields.Boolean(string="Needs Currency Recalc")
    no_request_required = fields.Boolean(string="Do not require order request", help="When set, orders under this contract are not checked for the customer transport order document")
    notes = fields.Text(string="Additional Notes")
    number = fields.Char(string="Number", required=True)
    our_authority_text = fields.Char(string="Authority Text(our)", translate=True)
    our_signed_by_partner_id = fields.Many2one(string="Signed by(our)", comodel_name="res.partner")
    oversized_penalty = fields.Monetary(string="Oversized Penalty", currency_field="currency_id")
    partner_id = fields.Many2one(string="Partner", required=True, comodel_name="res.partner")
    payment_currency_compute_rule = fields.Selection(string="Payment Currency Compute Rule", selection=[("placeholder", "Placeholder")])
    payment_currency_id = fields.Many2one(string="Payment Currency", help="Currency in which payment is expected from the counterparty.", comodel_name="res.currency")
    payment_term_id = fields.Many2one(string="Payment Terms", comodel_name="account.payment.term")
    payment_term_verbose = fields.Char(string="Verbose Term", readonly=True, store=False)
    ref_penalty = fields.Monetary(string="Ref Penalty", currency_field="currency_id")
    report_name = fields.Char(string="Report Name", readonly=True, store=False)
    required_doc_type_ids = fields.Many2many(string="Required Docs for Order", help="Choose Document Types required by default for new Orders", comodel_name="ufs.transport.document.type")
    service_name_contract = fields.Boolean(string="Contract in Name")
    service_name_documents = fields.Boolean(string="Documents in Name")
    service_name_driver = fields.Boolean(string="Driver in Name")
    service_name_incoming_ref = fields.Boolean(string="Incoming Ref. in Name")
    service_name_loading_date = fields.Boolean(string="Load Date in Name")
    service_name_unloading_date = fields.Boolean(string="Unload Date in Name")
    service_name_vehicle = fields.Boolean(string="Vehicle in Name")
    sign_date = fields.Date(string="Sign Date", required=True)
    tilt_penalty = fields.Monetary(string="Tilt Penalty", currency_field="currency_id")
    u_guid = fields.Char(string="GUID")
    ufs_payment_term_id = fields.Many2one(string="Payment Terms", comodel_name="ufs.payment.term")
    use_contract_checks = fields.Boolean(string="Use Contract Checks", readonly=True, store=False)
    use_doc_params = fields.Boolean(string="Override Invoice Line Name Params", help="When enabled, contract-level parameters override the global service name composition settings.")
    company_partner_id = fields.Many2one(string="Partner", readonly=True, store=False, comodel_name="res.partner", related="company_id.partner_id")
    is_business_day_term = fields.Boolean(string="Is Business Day Term", readonly=True, store=False, related="ufs_payment_term_id.is_business_day_term")
    is_n_term = fields.Boolean(string="Is N term", readonly=True, store=False, related="ufs_payment_term_id.is_n_term")

class UfsContractDocPreference(models.Model):
    _name = "ufs.contract.doc.preference"
    _description = "Contract Document Delivery Preference"
    _order = "doc_type_id"
    by_edi = fields.Boolean(string="By EDI")
    by_email = fields.Boolean(string="By Email")
    by_post = fields.Boolean(string="By Post")
    contract_id = fields.Many2one(string="Contract", required=True, comodel_name="ufs.contract")
    doc_type_id = fields.Many2one(string="Document Type", required=True, comodel_name="ufs.transport.document.type")
    docs_email = fields.Char(string="Email for Documents")
    postal_contact_name = fields.Char(string="Postal Contact (FIO)")
    postal_contact_phone = fields.Char(string="Postal Contact Phone")
