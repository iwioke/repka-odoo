@tagged("post_install", "-at_install")
class TestStandardModules(TransactionCase):
    def test_source_standard_modules_are_installed(self):
        modules = self.env["ir.module.module"].search([
            ("name", "in", sorted(SOURCE_STANDARD_MODULES)),
        ])
        installed = set(modules.filtered(lambda module: module.state == "installed").mapped("name"))

        self.assertEqual(SOURCE_STANDARD_MODULES - installed, set())
