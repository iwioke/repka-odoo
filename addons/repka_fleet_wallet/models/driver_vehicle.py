    statement_id = fields.Many2one(string="Statement", comodel_name="account.bank.statement")
    trip_id = fields.Many2one(string="Trip", comodel_name="ufs.fleet.trip")
    u_guid = fields.Char(string="GUID")
    vault_id = fields.Many2one(string="Vault", comodel_name="ufs.wallet.vault")
    waybill_id = fields.Many2one(string="Waybill", comodel_name="ufs.waybill")
    base_currency_id = fields.Many2one(string="Base Currency", readonly=True, comodel_name="res.currency", related="company_id.base_currency_id")
    company_currency_id = fields.Many2one(string="Currency", readonly=True, comodel_name="res.currency", related="company_id.currency_id")
    company_id = fields.Many2one(string="Company", readonly=True, comodel_name="res.company", related="employee_id.company_id")
    employee_id = fields.Many2one(string="Driver", required=True, readonly=True, store=False, comodel_name="hr.employee", related="payroll_id.employee_id")
    person_id = fields.Many2one(string="Partner", readonly=True, comodel_name="res.partner", related="employee_id.physical_person_id")

