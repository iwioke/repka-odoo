from odoo import fields, models

class UfsDriverPayroll(models.Model):
    _name = "ufs.driver.payroll"
    _description = "Driver Payroll"
    _order = "payroll_date desc"
    _inherit = ['mail.thread', 'mail.activity.mixin']
    advance_line_amount = fields.Monetary(string="Advances", readonly=True, currency_field="base_currency_id")
    advance_line_ids = fields.One2many(string="Advances", comodel_name="ufs.driver.payroll.advance_line", inverse_name="payroll_id")
    comments = fields.Text(string="Comments")
    employee_id = fields.Many2one(string="Driver", required=True, comodel_name="hr.employee")
    end_balance = fields.Monetary(string="End Balance", readonly=True, currency_field="base_currency_id")
    has_message = fields.Boolean(string="Has Message", readonly=True, store=False)
    name = fields.Char(string="Number")
    payroll_date = fields.Date(string="Date", required=True)
    period_end_date = fields.Date(string="Period End Date", required=True)
    period_start_date = fields.Date(string="Period Start Date", required=True)
    start_balance = fields.Monetary(string="Start Balance", currency_field="base_currency_id")
    state = fields.Selection(string="Status", selection=[("placeholder", "Placeholder")])
    to_be_paid_amount = fields.Monetary(string="To Be Paid Amount", currency_field="base_currency_id")
    to_collect_amount = fields.Monetary(string="To Collect Amount", readonly=True, currency_field="base_currency_id")
    trip_ids = fields.Many2many(string="Trips", comodel_name="ufs.fleet.trip")
    trips_amount = fields.Monetary(string="Trips Amount", readonly=True, currency_field="base_currency_id")
    base_currency_id = fields.Many2one(string="Base Currency", readonly=True, comodel_name="res.currency", related="company_id.base_currency_id")
    company_id = fields.Many2one(string="Company", readonly=True, comodel_name="res.company", related="employee_id.company_id")

